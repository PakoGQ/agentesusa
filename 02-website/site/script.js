let currentLang = 'en';

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Update text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (translations[key] && translations[key][lang]) {
      // Check if it has data-i18n-attr (for attributes like content)
      const attr = el.dataset.i18nAttr;
      if (attr) {
        el.setAttribute(attr, translations[key][lang]);
      } else {
        el.innerHTML = translations[key][lang];
      }
    }
  });

  // Update language toggle buttons
  document.getElementById('lang-en').classList.toggle('bg-slate-700', lang === 'en');
  document.getElementById('lang-en').classList.toggle('text-white', lang === 'en');
  document.getElementById('lang-en').classList.toggle('text-slate-400', lang !== 'en');

  document.getElementById('lang-es').classList.toggle('bg-slate-700', lang === 'es');
  document.getElementById('lang-es').classList.toggle('text-white', lang === 'es');
  document.getElementById('lang-es').classList.toggle('text-slate-400', lang !== 'es');

  // Update pricing display
  setVertical(currentVertical);

  // Sync typewriter to new language
  if (window._updateTypewriter) window._updateTypewriter(lang);

  // Save preference
  localStorage.setItem('nexus_lang', lang);
}

